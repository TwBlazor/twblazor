using System.Text;

namespace TwBlazor.Docs.Compiler;

/// <summary>
/// Generates C# code for the CodeExamples class
/// </summary>
public static class CodeGenerator
{
    /// <summary>
    /// Generates the CodeExamples class from &lt;CodeExample&gt; and
    /// "#region CodeExample" snippets extracted directly out of the docs pages.
    /// </summary>
    public static string GenerateCodeExamplesClass(Dictionary<string, string> examples)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// This file is automatically generated by TwBlazor.Docs.Compiler");
        sb.AppendLine("// Do not edit this file manually as your changes will be overwritten");
        sb.AppendLine();
        sb.AppendLine("namespace TwBlazor.Docs.Generated;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated code samples extracted from CodeExample blocks in the docs pages");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class CodeExamples");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly Dictionary<string, string> _examples = new()");
        sb.AppendLine("    {");

        foreach (var kvp in examples.OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            sb.AppendLine($"        [\"{kvp.Key}\"] = @\"{EscapeString(kvp.Value)}\",");
        }

        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    public static string Get(string name) =>");
        sb.AppendLine("        _examples.TryGetValue(name, out var value) ? value : $\"// CodeExample '{name}' not found\";");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static string EscapeString(string str)
    {
        return str.Replace("\"", "\"\"");
    }
}
