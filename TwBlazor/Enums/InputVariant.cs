namespace TwBlazor.Enums;

/// <summary>
/// Represents the visual style variant for input components.
/// </summary>
public enum InputVariant
{
    /// <summary>
    /// Default variant with bottom border only.
    /// </summary>
    Default,

    /// <summary>
    /// Outlined variant with border on all sides.
    /// </summary>
    Outlined,

    /// <summary>
    /// Filled variant with background color and bottom border.
    /// </summary>
    Filled
}
