    /// No shadow (0dp elevation).
    /// </summary>
    None,

    /// <summary>
    /// Small shadow (2dp elevation).
    /// </summary>
    Sm,

    /// <summary>
    /// Medium shadow (4dp elevation).
    /// </summary>
    Md,

    /// <summary>
    /// Large shadow (8dp elevation).
    /// </summary>
    Lg
}
