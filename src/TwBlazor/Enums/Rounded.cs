namespace TwBlazor.Enums;

/// <summary>
/// Represents border radius values.
/// </summary>
public enum Rounded
{
    /// <summary>
    /// No border radius (sharp corners).
    /// </summary>
    None,

    /// <summary>
    /// Small border radius (2px).
    /// </summary>
    Sm,

    /// <summary>
    /// Medium border radius (4px).
    /// </summary>
    Md,

    /// <summary>
    /// Large border radius (8px).
    /// </summary>
    Lg,

    /// <summary>
    /// Fully rounded/circular.
    /// </summary>
    Full
}
